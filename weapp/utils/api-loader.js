// utils/api-loader.js
// API动态加载器 - 避免主包包含未使用的JS文件

const apis = {};

module.exports = {
  // 动态获取API模块
  get(name) {
    if (!apis[name]) {
      apis[name] = require(`../api/${name}`);
    }
    return apis[name];
  },
  
  // 预加载指定API（在分包页面onLoad中调用）
  preload(names) {
    names.forEach(name => this.get(name));
  }
};
